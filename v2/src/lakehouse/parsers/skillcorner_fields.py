"""The SkillCorner open-data source fields and their types (spec §12.1, §12.2; plan Task 17).

These declarations are the field inventory of the 20 public A-League 2024/25 matches of GitHub `SkillCorner/opendata`,
read on 2026-10-27: every column of `{id}_dynamic_events.csv` and `{id}_phases_of_play.csv` (the headers of all 20
files are identical), and every field path of `{id}_match.json` and `matches.json`. A column or path outside these
declarations fails the match loudly (`UnmappedFieldError`, §12.3). CSV kinds follow the values of all 20 files:
`bool` for `True`/`False`, `int` for plain integers, `mm` for pitch coordinates in metres, `clock_ds` for the
`MM:SS.d` match clock, `float` for every other decimal, `str` otherwise.
"""

