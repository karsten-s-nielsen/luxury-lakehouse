_I64: Final = pa.int64()
_STR: Final = pa.string()
_F64: Final = pa.float64()
_UTC: Final = pa.timestamp("us", tz="UTC")


def _team(side: str) -> tuple[Field, ...]:
    team, kit = f"{side}_team", f"{side}_team_kit"
    return (
        Field(f"{team}_id", f"{team}.id", _I64),
        Field(f"{team}_name", f"{team}.name", _STR),
        Field(f"{team}_short_name", f"{team}.short_name", _STR),
        Field(f"{team}_acronym", f"{team}.acronym", _STR),
        Field(f"{kit}_id", f"{kit}.id", _I64),
        Field(f"{kit}_team_id", f"{kit}.team_id", _I64),
        Field(f"{kit}_season_id", f"{kit}.season.id", _I64),
        Field(f"{kit}_season_start_year", f"{kit}.season.start_year", _I64),
        Field(f"{kit}_season_end_year", f"{kit}.season.end_year", _I64),
        Field(f"{kit}_season_name", f"{kit}.season.name", _STR),
        Field(f"{kit}_name", f"{kit}.name", _STR),
        Field(f"{kit}_jersey_color", f"{kit}.jersey_color", _STR),
        Field(f"{kit}_number_color", f"{kit}.number_color", _STR),
        # null in the public files; an object in the pining owner tier's metadata.json (measured 2026-10-27)
        Field(f"{team}_coach_id", f"{team}_coach.id", _I64),
        Field(f"{team}_coach_first_name", f"{team}_coach.first_name", _STR),
        Field(f"{team}_coach_last_name", f"{team}_coach.last_name", _STR),
        Field(f"{team}_playing_time_minutes_tip", f"{team}_playing_time.minutes_tip", _F64),
        Field(f"{team}_playing_time_minutes_otip", f"{team}_playing_time.minutes_otip", _F64),
    )


