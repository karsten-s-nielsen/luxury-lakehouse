def test_owner_tier_fields_mapped() -> None:
    parser = SkillCornerParser()
    assert unmapped_fields(OWNER_MATCH_FIELDS, parser.bronze_columns("match")) == []
    assert OWNER_EVENTS_ABSENT <= parser.bronze_columns("dynamic_events_parquet")
    assert parser.bronze_columns("physical") == OWNER_PHYSICAL_COLUMNS
    assert parser.bronze_columns("tracking_parquet") == parser.bronze_columns("tracking")


@pytest.mark.parametrize(
    ("artifact", "name"),
    [
        ("tracking_parquet", "tracking_1899585_slice.parquet"),
        ("dynamic_events_parquet", "dynamic_events_1899585_slice.parquet"),
        ("physical", "physical_1899585_synthetic.parquet"),
    ],
)
def test_format_2_fixtures_mapped(artifact: str, name: str) -> None:
    parser = SkillCornerParser()
    inventory = parser.field_inventory(artifact, (FIXTURES / name).read_bytes())
    assert inventory
    assert unmapped_fields(inventory, parser.bronze_columns(artifact)) == []
    if artifact == "physical":
        assert inventory == OWNER_PHYSICAL_COLUMNS
