@pytest.mark.parametrize("artifact", list(FIXTURE_FILES))
def test_field_inventory_complete(artifact: str) -> None:
    parser = SkillCornerParser()
    columns = parser.bronze_columns(artifact)
    assert unmapped_fields(EXPECTED_FIELDS[artifact], columns) == []
    found: set[str] = set()
    for name in FIXTURE_FILES[artifact]:
        inventory = parser.field_inventory(artifact, (FIXTURES / name).read_bytes())
        assert unmapped_fields(inventory, columns) == [], name
        found |= inventory
    assert found == EXPECTED_FIELDS[artifact]  # the fixtures hold every observed field


@pytest.mark.parametrize(
    ("artifact", "name", "old", "new", "path"),
    [
        ("match", "match_1899585.json", b'"status":', b'"weather": "dry", "status":', "weather"),
        (
            "match",
            "match_1899585.json",
            b'"team_player_id":',
            b'"nationality": "AUS", "team_player_id":',
            "players[].nationality",
        ),
        ("dynamic_events", "dynamic_events_1899585_slice.csv", b"event_id,", b"new_metric,event_id,", "new_metric"),
        ("tracking", "tracking_1899585_slice.jsonl", b'"frame": 0,', b'"frame": 0, "camera": 1,', "camera"),
    ],
)
def test_unmapped_field_fails_loudly(artifact: str, name: str, old: bytes, new: bytes, path: str) -> None:
    data = (FIXTURES / name).read_bytes()
    assert data.count(old) >= 1
    changed = data.replace(old, new, 1)
    if artifact == "dynamic_events":  # one more field in every record, so the CSV stays well formed
        lines = changed.split(b"\n")
        changed = b"\n".join([lines[0], *(b"1," + line if line else line for line in lines[1:])])
    with pytest.raises(UnmappedFieldError) as caught:
        parse_with(**{artifact: changed})
    assert path in caught.value.field_paths


