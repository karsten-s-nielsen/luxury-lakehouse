def _read(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


@pytest.mark.parametrize("artifact", ["metadata", "events", "positions"])
def test_field_inventory_complete(artifact: str) -> None:
    parser = IdsseParser()
    columns = parser.bronze_columns(artifact)
    assert columns == EXPECTED_FIELDS[artifact]
    found: set[str] = set()
    for name in FIXTURE_FILES[artifact]:
        inventory = parser.field_inventory(artifact, _read(name))
        assert inventory <= columns, sorted(inventory - columns)
        found |= inventory
    assert found == EXPECTED_FIELDS[artifact]  # the fixtures hold every observed path


